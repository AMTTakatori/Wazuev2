create or replace function public.reserve_purchase(p_username text,p_product_id bigint)
returns jsonb language plpgsql security definer set search_path=public as $$
declare p products%rowtype; u users%rowtype; code text; oid bigint; nb bigint;
begin
 select * into p from products where id=p_product_id and active=true for share; if not found then raise exception 'Sản phẩm không tồn tại'; end if;
 select * into u from users where username=p_username for update; if not found then raise exception 'Tài khoản không tồn tại'; end if;
 if u.balance < p.price then raise exception 'Số dư không đủ'; end if;
 code:='WZ'||upper(substr(md5(random()::text||clock_timestamp()::text),1,10));
 nb:=u.balance-p.price; update users set balance=nb where username=p_username;
 insert into orders(username,order_code,product_id,product_name,amount,status) values(p_username,code,p.id,p.name,p.price,'PENDING') returning id into oid;
 insert into wallet_transactions(username,type,amount,reference,status) values(p_username,'PURCHASE',-p.price,code,'COMPLETED');
 return jsonb_build_object('success',true,'orderId',oid,'orderCode',code,'balance',nb);
end $$;

create or replace function public.complete_purchase(p_order_id bigint,p_account text)
returns boolean language plpgsql security definer set search_path=public as $$
begin update orders set status='COMPLETED',account=p_account,completed_at=now() where id=p_order_id and status='PENDING'; return found; end $$;

create or replace function public.cancel_purchase(p_order_id bigint)
returns boolean language plpgsql security definer set search_path=public as $$
declare o orders%rowtype; begin select * into o from orders where id=p_order_id for update; if not found or o.status<>'PENDING' then return false; end if; update orders set status='CANCELLED' where id=o.id; update users set balance=balance+o.amount where username=o.username; insert into wallet_transactions(username,type,amount,reference) values(o.username,'REFUND',o.amount,o.order_code); return true; end $$;
