create or replace function public.credit_deposit(p_deposit_id bigint,p_transaction_id text)
returns boolean language plpgsql security definer set search_path=public as $$
declare d deposits%rowtype; done boolean;
begin
  select * into d from deposits where id=p_deposit_id for update;
  if not found or d.status <> 'PENDING' then return false; end if;
  if p_transaction_id is not null and exists(select 1 from deposits where provider_transaction_id=p_transaction_id) then return false; end if;
  update deposits set status='COMPLETED',provider_transaction_id=nullif(p_transaction_id,''),completed_at=now() where id=d.id;
  update users set balance=balance+d.amount where username=d.username;
  insert into wallet_transactions(username,type,amount,reference) values(d.username,'DEPOSIT',d.amount,coalesce(nullif(p_transaction_id,''),d.trans_code));
  return true;
end $$;

create or replace function public.purchase_product(p_username text,p_product_id bigint)
returns jsonb language plpgsql security definer set search_path=public as $$
declare p products%rowtype; u users%rowtype; code text;
begin
  select * into p from products where id=p_product_id and active=true for share;
  if not found then raise exception 'Sản phẩm không tồn tại'; end if;
  select * into u from users where username=p_username for update;
  if not found then raise exception 'Tài khoản không tồn tại'; end if;
  if u.balance < p.price then raise exception 'Số dư không đủ'; end if;
  code := 'WZ'||upper(substr(md5(random()::text||clock_timestamp()::text),1,10));
  update users set balance=balance-p.price where username=p_username;
  insert into orders(username,order_code,product_id,product_name,amount,status) values(p_username,code,p.id,p.name,p.price,'PENDING');
  insert into wallet_transactions(username,type,amount,reference) values(p_username,'PURCHASE',-p.price,code);
  return jsonb_build_object('success',true,'orderCode',code,'balance',u.balance-p.price,'product',p.name);
end $$;

