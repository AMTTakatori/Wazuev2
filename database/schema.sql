-- Wazue v2 database. Run in a fresh Supabase project.
create table if not exists public.users (
  username text primary key,
  password_hash text not null,
  balance bigint not null default 0 check (balance >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.sessions (
  id bigint generated by default as identity primary key,
  username text not null references public.users(username) on delete cascade,
  token_hash text not null unique,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);
create index if not exists sessions_username_idx on public.sessions(username);
create index if not exists sessions_expiry_idx on public.sessions(expires_at);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  description text not null default '',
  category text not null default 'Khác',
  price bigint not null check (price > 0),
  days integer,
  provider text not null default 'manual',
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.deposits (
  id bigint generated by default as identity primary key,
  username text not null references public.users(username) on delete cascade,
  trans_code text not null unique,
  amount bigint not null check (amount > 0),
  status text not null default 'PENDING' check (status in ('PENDING','COMPLETED','CANCELLED')),
  provider_transaction_id text unique,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  username text not null references public.users(username) on delete cascade,
  order_code text not null unique,
  product_id bigint references public.products(id),
  product_name text not null,
  amount bigint not null check (amount > 0),
  status text not null default 'PENDING' check (status in ('PENDING','COMPLETED','CANCELLED','FAILED')),
  account text,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

create table if not exists public.wallet_transactions (
  id bigint generated by default as identity primary key,
  username text not null references public.users(username) on delete cascade,
  type text not null check (type in ('DEPOSIT','PURCHASE','REFUND','ADJUSTMENT')),
  amount bigint not null,
  reference text,
  status text not null default 'COMPLETED',
  created_at timestamptz not null default now()
);
create unique index if not exists wallet_reference_unique on public.wallet_transactions(type,reference) where reference is not null;

alter table public.users enable row level security;
alter table public.sessions enable row level security;
alter table public.products enable row level security;
alter table public.deposits enable row level security;
alter table public.orders enable row level security;
alter table public.wallet_transactions enable row level security;

